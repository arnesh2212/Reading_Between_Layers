"""Static registry of model specs declaring family, tier, and pretraining attributes."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

ModelFamily = Literal["encoder", "decoder", "encoder_decoder", "ssm", "sentence_transformer"]
ModelTier = Literal["A", "B", "C"]


@dataclass(frozen=True)
class ModelSpec:
    """Static description of one model in the registry."""

    name: str
    hf_id: str
    family: ModelFamily
    size_tier: ModelTier
    hidden_size: int
    num_layers: int
    has_cls: bool
    supports_chat_template: bool
    pretraining_objective: str
    pretraining_data_tag: str
    notes: str = ""
    trust_remote_code: bool = False


def _spec(**kwargs: object) -> ModelSpec:
    """Internal helper that defaults rare fields to keep entries terse."""
    return ModelSpec(**kwargs)  # type: ignore[arg-type]


