MODEL_REGISTRY: dict[str, ModelSpec] = {
    spec.name: spec
    for spec in (
        _ENCODER_MODELS
        + _SENTENCE_TRANSFORMER_MODELS
        + _DECODER_MODELS
        + _SSM_MODELS
        + _ENCODER_DECODER_MODELS
    )
}


def get_model_spec(name: str) -> ModelSpec:
    """Return the registered spec for ``name``.

    Raises:
        KeyError: if no model with that short name is registered.
    """
    return MODEL_REGISTRY[name]


def list_models_by_family(family: str) -> list[ModelSpec]:
    """Return every registered model whose family equals ``family``."""
    return [spec for spec in MODEL_REGISTRY.values() if spec.family == family]


def list_models_by_tier(tier: str) -> list[ModelSpec]:
    """Return every registered model whose size_tier equals ``tier``."""
    return [spec for spec in MODEL_REGISTRY.values() if spec.size_tier == tier]


def list_all_models() -> list[ModelSpec]:
    """Return every registered model."""
    return list(MODEL_REGISTRY.values())
